-- Vostrogate single-company ERP schema; all business data and binary branding live in MySQL.
CREATE TABLE IF NOT EXISTS schema_migrations (id INT PRIMARY KEY, applied_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6));
CREATE TABLE IF NOT EXISTS company (
  id TINYINT UNSIGNED NOT NULL PRIMARY KEY DEFAULT 1,
  legal_name VARCHAR(240) NOT NULL, trade_name VARCHAR(240) NOT NULL,
  ice VARCHAR(60) NOT NULL DEFAULT '', tax_id VARCHAR(60) NOT NULL DEFAULT '', rc VARCHAR(60) NOT NULL DEFAULT '', patente VARCHAR(60) NOT NULL DEFAULT '',
  address TEXT NOT NULL, city VARCHAR(140) NOT NULL DEFAULT '', phone VARCHAR(70) NOT NULL DEFAULT '', email VARCHAR(255) NOT NULL DEFAULT '',
  currency CHAR(3) NOT NULL DEFAULT 'MAD', language VARCHAR(8) NOT NULL DEFAULT 'fr', vat_default_bps INT NOT NULL DEFAULT 2000,
  logo MEDIUMBLOB NULL, logo_mime VARCHAR(100) NULL, env_path VARCHAR(1024) NOT NULL DEFAULT '',
  installed_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  CONSTRAINT company_singleton CHECK (id=1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS settings (
  setting_key VARCHAR(140) PRIMARY KEY, setting_json JSON NOT NULL, updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS roles (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) NOT NULL UNIQUE, label VARCHAR(120) NOT NULL, is_system BOOLEAN NOT NULL DEFAULT FALSE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS permissions (
  code VARCHAR(120) PRIMARY KEY, description VARCHAR(240) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS role_permissions (
  role_id BIGINT NOT NULL, permission_code VARCHAR(120) NOT NULL,
  PRIMARY KEY(role_id,permission_code), FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE CASCADE,
  FOREIGN KEY (permission_code) REFERENCES permissions(code) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS users (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, full_name VARCHAR(180) NOT NULL, username VARCHAR(80) NOT NULL UNIQUE,
  email VARCHAR(255) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
  role_id BIGINT NOT NULL, is_active BOOLEAN NOT NULL DEFAULT TRUE, is_owner_admin BOOLEAN NOT NULL DEFAULT FALSE,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  FOREIGN KEY (role_id) REFERENCES roles(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS sessions (
  token_hash BINARY(32) PRIMARY KEY, user_id BIGINT NOT NULL, csrf_hash BINARY(32) NOT NULL,
  expires_at DATETIME(6) NOT NULL, created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  KEY idx_sessions_expire (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS warehouses (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) NOT NULL UNIQUE, name VARCHAR(180) NOT NULL, is_default BOOLEAN NOT NULL DEFAULT FALSE, is_active BOOLEAN NOT NULL DEFAULT TRUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS reference_values (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, kind ENUM('category','brand','unit','price_group','expense_category') NOT NULL,
  name VARCHAR(180) NOT NULL, is_active BOOLEAN NOT NULL DEFAULT TRUE, UNIQUE KEY uq_ref (kind,name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS parties (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, kind ENUM('CUSTOMER','SUPPLIER') NOT NULL,
  code VARCHAR(50) NOT NULL, name VARCHAR(220) NOT NULL, phone VARCHAR(60) NOT NULL DEFAULT '', email VARCHAR(255) NOT NULL DEFAULT '',
  ice VARCHAR(65) NOT NULL DEFAULT '', tax_id VARCHAR(65) NOT NULL DEFAULT '', address TEXT NOT NULL,
  city VARCHAR(150) NOT NULL DEFAULT '', credit_limit_cents BIGINT NOT NULL DEFAULT 0, is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_party_code (kind,code), KEY idx_party_name (kind,name), FULLTEXT KEY ft_party_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS products (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, sku VARCHAR(90) NOT NULL UNIQUE, barcode VARCHAR(100) NULL UNIQUE,
  name VARCHAR(255) NOT NULL, description TEXT NOT NULL,
  category_id BIGINT NULL, brand_id BIGINT NULL, unit_id BIGINT NULL,
  purchase_price_cents BIGINT NOT NULL DEFAULT 0, sale_price_cents BIGINT NOT NULL DEFAULT 0,
  vat_bps INT NOT NULL DEFAULT 2000, min_stock_milli BIGINT NOT NULL DEFAULT 0,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  FOREIGN KEY (category_id) REFERENCES reference_values(id) ON DELETE SET NULL,
  FOREIGN KEY (brand_id) REFERENCES reference_values(id) ON DELETE SET NULL,
  FOREIGN KEY (unit_id) REFERENCES reference_values(id) ON DELETE SET NULL,
  KEY idx_products_name (name), FULLTEXT KEY ft_products_name (name,description)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS stock_balances (
  warehouse_id BIGINT NOT NULL, product_id BIGINT NOT NULL, quantity_milli BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY (warehouse_id,product_id), FOREIGN KEY (warehouse_id) REFERENCES warehouses(id),
  FOREIGN KEY (product_id) REFERENCES products(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS documents (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  doc_type ENUM('QUOTE','ORDER','DELIVERY','INVOICE','CREDIT','RETURN','PURCHASE_ORDER','PURCHASE_RECEIPT','PURCHASE_INVOICE') NOT NULL,
  doc_number VARCHAR(70) NOT NULL, status ENUM('DRAFT','FINAL','CANCELLED') NOT NULL DEFAULT 'DRAFT',
  party_id BIGINT NOT NULL, warehouse_id BIGINT NOT NULL, source_document_id BIGINT NULL,
  issued_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), finalized_at DATETIME(6) NULL,
  subtotal_cents BIGINT NOT NULL DEFAULT 0, vat_cents BIGINT NOT NULL DEFAULT 0, total_cents BIGINT NOT NULL DEFAULT 0,
  paid_cents BIGINT NOT NULL DEFAULT 0, notes TEXT NOT NULL, created_by BIGINT NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6), updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE KEY uq_doc_type_no (doc_type,doc_number), UNIQUE KEY uq_doc_conversion(source_document_id,doc_type), KEY idx_doc_party (party_id,doc_type,status),
  KEY idx_doc_source (source_document_id),
  FOREIGN KEY (party_id) REFERENCES parties(id), FOREIGN KEY (warehouse_id) REFERENCES warehouses(id),
  FOREIGN KEY (source_document_id) REFERENCES documents(id), FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS document_sequences (
  doc_type VARCHAR(40) PRIMARY KEY, next_number BIGINT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS document_lines (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, document_id BIGINT NOT NULL, product_id BIGINT NOT NULL,
  sku_snapshot VARCHAR(90) NOT NULL, name_snapshot VARCHAR(255) NOT NULL,
  qty_milli BIGINT NOT NULL, unit_price_cents BIGINT NOT NULL, discount_bps INT NOT NULL DEFAULT 0,
  vat_bps INT NOT NULL DEFAULT 0, subtotal_cents BIGINT NOT NULL, vat_cents BIGINT NOT NULL, total_cents BIGINT NOT NULL,
  FOREIGN KEY (document_id) REFERENCES documents(id) ON DELETE CASCADE, FOREIGN KEY (product_id) REFERENCES products(id),
  KEY idx_docline_doc (document_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS stock_movements (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, warehouse_id BIGINT NOT NULL, product_id BIGINT NOT NULL, document_line_id BIGINT NULL,
  movement_key VARCHAR(150) NOT NULL UNIQUE, delta_milli BIGINT NOT NULL,
  reason VARCHAR(140) NOT NULL, actor_id BIGINT NOT NULL, created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY (warehouse_id) REFERENCES warehouses(id), FOREIGN KEY (product_id) REFERENCES products(id),
  FOREIGN KEY (document_line_id) REFERENCES document_lines(id), FOREIGN KEY (actor_id) REFERENCES users(id),
  KEY idx_stock_history (product_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS stock_adjustments (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, warehouse_id BIGINT NOT NULL, product_id BIGINT NOT NULL, delta_milli BIGINT NOT NULL,
  reason VARCHAR(240) NOT NULL, actor_id BIGINT NOT NULL, created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY (warehouse_id) REFERENCES warehouses(id), FOREIGN KEY (product_id) REFERENCES products(id), FOREIGN KEY (actor_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS payments (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, document_id BIGINT NOT NULL, party_id BIGINT NOT NULL,
  amount_cents BIGINT NOT NULL, method ENUM('CASH','TRANSFER','CARD','CHEQUE','EFFECT') NOT NULL,
  reference VARCHAR(120) NOT NULL DEFAULT '', bank VARCHAR(140) NOT NULL DEFAULT '', due_date DATE NULL,
  status ENUM('PENDING','CLEARED','REJECTED') NOT NULL, received_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  created_by BIGINT NOT NULL, created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY (document_id) REFERENCES documents(id), FOREIGN KEY (party_id) REFERENCES parties(id), FOREIGN KEY (created_by) REFERENCES users(id),
  KEY idx_payment_doc (document_id,status), KEY idx_payment_due (status,due_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS expenses (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, title VARCHAR(220) NOT NULL, category_id BIGINT NULL,
  amount_cents BIGINT NOT NULL, spent_on DATE NOT NULL, method VARCHAR(50) NOT NULL DEFAULT 'CASH', notes TEXT NOT NULL,
  created_by BIGINT NOT NULL, created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY (category_id) REFERENCES reference_values(id) ON DELETE SET NULL, FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit_log (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, actor_id BIGINT NULL, action VARCHAR(90) NOT NULL, entity_type VARCHAR(90) NOT NULL,
  entity_id BIGINT NOT NULL DEFAULT 0, details_json JSON NULL, created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  KEY idx_audit_created (created_at), FOREIGN KEY (actor_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
